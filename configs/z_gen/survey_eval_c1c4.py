#!/usr/bin/env python3
"""Emit the C1-C4 candidate val confs (2026-10-25, ckpt规则.md 第一阶段).

Four val cam3 three-condition evaluations on the existing survey snapshots —
no training, no test.  The runner's survey_eval task (SPLIT=val) writes
receipts with checkpoint/config sha256 and completion guards.
"""

from __future__ import annotations

from common import QUEUE_DIR, REPO, _next_sequence

CANDIDATES = (
    # (model_id, ckpt path relative to repo, label)
    ("V5_Av4_wo05_survey_drop",
     "results/AnySole/V5_Av4_wo05_survey_drop_f6_soft/tw20_st20_lr0.0001_lp3_lt1_lk1_wu0.05_gc5_ep740_bs256_sd1/checkpoints/checkpoints/survey/survey_ep735.pt",
     "C1"),
    ("V5_Av4_wo05_survey_drop",
     "results/AnySole/V5_Av4_wo05_survey_drop_f6_soft/tw20_st20_lr0.0001_lp3_lt1_lk1_wu0.05_gc5_ep740_bs256_sd1/checkpoints/checkpoints/survey/survey_ep690.pt",
     "C2"),
    ("V5_Av4_wo05_survey_drop",
     "results/AnySole/V5_Av4_wo05_survey_drop_f6_soft/tw20_st20_lr0.0001_lp3_lt1_lk1_wu0.05_gc5_ep740_bs256_sd1/checkpoints/checkpoints/survey/survey_ep720.pt",
     "C3"),
    ("V4_Av1_wo05_survey_drop",
     "results/AnySole/V4_Av1_wo05_survey_drop_f6_soft/tw20_st20_lr0.0001_lp3_lt1_lk1_lpos3_wu0.05_gc5_ep740_bs256_sd1/checkpoints/checkpoints/survey/survey_ep105.pt",
     "C4"),
)


def main() -> int:
    seq = _next_sequence()
    count = 0
    for model_id, ckpt_rel, label in CANDIDATES:
        ckpt = (REPO / ckpt_rel).resolve()
        if not ckpt.is_file():
            raise FileNotFoundError("candidate checkpoint missing: %s" % ckpt)
        path = QUEUE_DIR / ("%05d__wo05_survey_eval__%s__%s__cam3.conf"
                            % (seq, model_id, ckpt.stem))
        path.write_text("\n".join([
            "# Generated by configs/z_gen/survey_eval_c1c4.py (%s)" % label,
            "EXPERIMENT_ID=wo05_survey_eval",
            "TASK=survey_eval",
            "MODEL_ID=%s" % model_id,
            "CKPT_PATH=%s" % ckpt,
            "COND=cam3",
            "SPLIT=val",
            "FORCE=false",
            "",
        ]), encoding="utf-8")
        print("[queue] %s" % path)
        seq += 1
        count += 1
    print("emitted %d candidate val conf(s)" % count)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
