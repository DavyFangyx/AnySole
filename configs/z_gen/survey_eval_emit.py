#!/usr/bin/env python3
"""Emit wo05 survey series evaluation confs (2026-10-24, user ruling).

After the wo05_survey training confs reach done/, this scans each survey
model's checkpoints/survey/survey_ep{N}.pt series and emits one
TASK=survey_eval conf per (model, survey ckpt, condition). Candidate review
defaults to val on cam3 + occ010/020/030/050; test must be explicit.

The runner's survey_eval task resolves configs (cam3 -> the model's own
v1_wo05.yaml; occ -> v1_cam3_{cond}_wo05.yaml) and writes metrics into
results/experiments/wo05_survey/<model>/<ckpt_stem>/<cond>/metrics/.

Only an existing result for the requested split and checkpoint is skipped.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from common import QUEUE_DIR, REPO, _next_sequence
from configs.tools.common import sha256_file

CONDS = ("cam3", "occ010", "occ020", "occ030", "occ050")
SURVEY_MODELS = (
    "V4_Av1_wo05_survey",
    "V4_Av1_wo05_survey_drop",
    "V5_Av4_wo05_survey",
    "V5_Av4_wo05_survey_drop",
)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--models", default=",".join(SURVEY_MODELS),
                        help="comma-separated survey model IDs")
    parser.add_argument("--split", choices=("val", "test"), default="val",
                        help="Candidate selection uses val; test is explicit after fixing a checkpoint")
    parser.add_argument("--dry-run", action="store_true",
                        help="list the cells without writing confs")
    args = parser.parse_args()
    models = [m.strip() for m in args.models.split(",") if m.strip()]
    seq = _next_sequence()
    count = 0
    hashes = {}
    for model_id in models:
        model_dir = REPO / "results" / "AnySole" / (model_id + "_f6_soft")
        if not model_dir.is_dir():
            print("skip %s: no results dir" % model_id)
            continue
        ckpts = []
        for variant in model_dir.iterdir():
            # 2026-10-25 修复：首轮（01172–01175）写 checkpoints/checkpoints/
            # survey（train.py 旧路径 out_dir/"checkpoints"/"survey"，
            # out_dir 本身即 checkpoints 目录）；10-25 起 train.py 改平铺
            # checkpoints/survey。两处都扫，任一命中即可。
            for survey_dir in (variant / "checkpoints" / "survey",
                               variant / "checkpoints" / "checkpoints" / "survey"):
                if survey_dir.is_dir():
                    ckpts.extend(sorted(survey_dir.glob("survey_ep*.pt"),
                                        key=lambda p: int(p.stem.split("_ep")[1])))
        if not ckpts:
            print("skip %s: no survey checkpoints (training may still be running)" % model_id)
            continue
        for ckpt in ckpts:
            for cond in CONDS:
                metrics_dir = (REPO / "results" / "experiments" / "wo05_survey"
                               / model_id / ckpt.stem / cond / "metrics")
                if (metrics_dir / (args.split + ".json")).is_file():
                    result = json.loads((metrics_dir / (args.split + ".json")).read_text())
                    if result.get("split") != args.split or Path(result.get("checkpoint", "")).resolve() != ckpt.resolve():
                        raise ValueError("Existing evaluation has different provenance: %s" % metrics_dir)
                    receipt_path = metrics_dir / ("receipt.json" if args.split == "val" else "receipt_test.json")
                    if not receipt_path.is_file():
                        raise ValueError("Existing evaluation has no verified receipt; preserve and review it: %s" % metrics_dir)
                    receipt = json.loads(receipt_path.read_text())
                    if ckpt not in hashes:
                        hashes[ckpt] = sha256_file(ckpt)
                    if (receipt.get("status") != "complete" or receipt.get("split") != args.split
                            or receipt.get("checkpoint_sha256") != hashes[ckpt]):
                        raise ValueError("Existing evaluation checkpoint changed: %s" % metrics_dir)
                    continue
                path = QUEUE_DIR / ("%05d__wo05_survey_eval__%s__%s__%s.conf"
                                    % (seq, model_id, ckpt.stem, cond))
                if not args.dry_run:
                    path.write_text("\n".join([
                        "# Generated by configs/z_gen/survey_eval_emit.py",
                        "EXPERIMENT_ID=wo05_survey_eval",
                        "TASK=survey_eval",
                        "MODEL_ID=%s" % model_id,
                        "CKPT_PATH=%s" % ckpt,
                        "COND=%s" % cond,
                        "SPLIT=%s" % args.split,
                        "FORCE=false",
                        "",
                    ]), encoding="utf-8")
                print("[queue] %s" % path)
                seq += 1
                count += 1
    print("emitted %d survey_eval conf(s)" % count)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
